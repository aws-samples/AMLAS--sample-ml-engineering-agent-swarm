"""Runtime notice for a conversation that the runtime restored from its saved checkpoint.

The resumed Agent used to learn nothing about its restoration. The claimed Agent now gets one short factual notice appended to its system prompt, once,
after the start CAS of the continuation (`begin_completion_invocation`) has succeeded and before the single invocation. The system prompt is not part of
the SDK snapshot: the claimed messages, the snapshot hash stored in the continuation row and every qualification pass are unchanged. The notice states
only what the runtime knows (the checkpoint restore, the invoking epoch of the row, that the runtime supplied the pending call's result) and records no cause. It also asks the agent to state the restoration, as a fact and without a cause, in the persistence and recovery part of its final
report.

The restored run also leaves two runtime-written records that do not depend on the model. After the start CAS the continuation appends one
`## Runtime recovery record` block to the response message (`recovery_report_paragraph`, `append_recovery_report`). Its wording follows one
recorded fact, whether the original worker had saved a pause report when the replacement claimed the completion, and its three digests are
printed in groups of eight characters so that no decimal run longer than eight digits can occur. Right after the start CAS, before the first model
call, `log_restore_completed` writes one WARNING line (`normal_restore_completed ...`) that a log reader can match against the run row; a record that
cannot be built gives the closed fallback line `normal_restore_record_irregular ...`. Neither depends on the system-prompt notice, and a receipt of any
schema other than 3 gets neither.
"""

from __future__ import annotations

import hashlib
import json
import logging
import re

MARKER = "Runtime notice (restoration):"
_TOOL = "submit_qwen_sft"
_EPOCHS = (1, 2)
REPORT_HEADING = "## Runtime recovery record"
RESTORE_MARKER = "normal_restore_completed"
IRREGULAR_MARKER = "normal_restore_record_irregular"
_STAGE = "sft"  # the only continuation kind that reaches the start CAS
_HEX32 = re.compile(r"[a-f0-9]{32}")
_HEX64 = re.compile(r"[a-f0-9]{64}")
_REPORT_INTRO = (
    "This section was generated by the runtime from its continuation receipt; the model did not write it."
)
_REPORT_ABSENT = (
    "The worker invocation that began this run stopped before it saved any report, and the runtime recorded no cause for the stop. "
    "A replacement worker invocation then restored the run from its saved checkpoint and continued it as continuation epoch 2."
)
_REPORT_PRESENT = (
    "The worker invocation that began this run ended after saving its pause report. "
    "A later worker invocation restored the run from its saved checkpoint and continued it as continuation epoch 2."
)
_REPORT_UNKNOWN = (
    "The earlier worker invocation stopped executing this run before final completion. "
    "A replacement worker invocation restored the saved checkpoint and started continuation epoch 2. "
    "This receipt does not establish why the earlier invocation ended or whether a physical worker stop occurred; "
    "the same continuation path is used for an ordinary SFT pause and wake."
)
logger = logging.getLogger(__name__)


def recovery_notice(epoch: int) -> str:
    """The notice text for one continuation epoch; deterministic and free of identifiers."""
    if type(epoch) is not int or epoch not in _EPOCHS:
        raise ValueError("recovery notice epoch differs")
    return (
        "\n\n"
        + MARKER
        + " this conversation was restored by the runtime from its saved checkpoint in a new worker invocation (continuation invoking epoch "
        + str(epoch)
        + "); the invocation that made the "
        + _TOOL
        + " call has ended. The history before that call is unchanged, and the result of that call was supplied by the runtime after it verified "
        "the job completed. The restoration was not your action, and no cause is recorded here. Your final report must state this restoration as a fact, "
        "in the section where you describe persistence and recovery; it must not say that no restoration or worker interruption occurred, name a cause, "
        "or claim that you tested or built recovery."
    )


def _base_text(agent) -> str:
    """The current system prompt text of the Agent; an Agent built without one has an empty base.

    A prompt that is not text, or content blocks of another kind than text (a cache point), would be changed by writing a string
    back, so such an Agent is refused before anything is spent.
    """
    prompt = getattr(agent, "system_prompt", None)
    content = getattr(agent, "system_prompt_content", None)
    if prompt is not None and type(prompt) is not str:
        raise ValueError("restored Agent system prompt cannot take the recovery notice")
    if content is not None and (
        type(content) is not list
        or any(type(block) is not dict or set(block) != {"text"} for block in content)
    ):
        raise ValueError("restored Agent system prompt cannot take the recovery notice")
    return prompt or ""


def check_recovery_notice_ready(agent, context) -> None:
    """Everything that can fail without the epoch, checked before the single-use start CAS so a refusal burns nothing."""
    base = _base_text(agent)
    if MARKER in base:
        raise ValueError("restored Agent system prompt cannot take the recovery notice")
    completion_epoch(
        context
    )  # the claimed receipt reads now, so reading it again after the start CAS cannot fail
    for epoch in _EPOCHS:
        recovery_notice(epoch)
    _record_facts(
        context
    )  # a schema 3 receipt must carry readable ids now: the record builder cannot fail after the start CAS
    agent.system_prompt = getattr(agent, "system_prompt", None)  # the SDK setter accepts the assignment


def completion_epoch(context) -> int:
    """The epoch of the claimed continuation as the runtime recorded it (the invoking epoch after a successful start CAS)."""
    receipt = getattr(context, "_completion_receipt", None)
    if type(receipt) is not tuple or len(receipt) != 3 or type(receipt[1]) is not str:
        raise ValueError("claimed continuation receipt unavailable")
    owned = json.loads(receipt[1])
    epoch = owned.get("epoch") if type(owned) is dict else None
    if type(epoch) is not int or epoch not in _EPOCHS:
        raise ValueError("claimed continuation epoch differs")
    return epoch


def apply_recovery_notice(agent, context) -> bool:
    """Append the notice once; a second call is a no-op, an inconsistent earlier notice is refused."""
    base = _base_text(agent)
    epoch = completion_epoch(context)
    notice = recovery_notice(epoch)
    if MARKER in base:
        if base.count(MARKER) != 1 or not (base.endswith(notice) or base == notice.lstrip("\n")):
            raise ValueError("restored Agent carries an inconsistent recovery notice")
        return False
    agent.system_prompt = base + notice if base else notice.lstrip("\n")
    logger.info(
        "recovery_notice_applied epoch=%d sha256=%s",
        epoch,
        hashlib.sha256(notice.encode()).hexdigest()[:16],
    )
    return True


class _IrregularError(ValueError):
    """A receipt that cannot give a record; `reason` is the closed vocabulary of the fallback line."""

    def __init__(self, reason: str):
        super().__init__("claimed continuation receipt cannot give a recovery record: " + reason)
        self.reason = reason


def _hex64(value) -> str:
    if type(value) is not str or _HEX64.fullmatch(value) is None:
        raise _IrregularError("bad_digest")
    return value


def _record_facts(context):
    """The facts of a schema 3 receipt, or None for any other schema (a legacy receipt keeps the behaviour it had).

    A schema 3 receipt is `ready` at epoch 1 before the start CAS and `invoking` at epoch exactly 2 after it; every other combination, any id that is
    not 64 lowercase hex characters, a task descriptor that is not a JSON object with a `sha256`, and a recorded prior-report fact that is not a
    boolean (or None, for a claim that did not record it) raises `_IrregularError`, a `ValueError`.
    """
    receipt = getattr(context, "_completion_receipt", None)
    if type(receipt) is not tuple or len(receipt) != 3 or type(receipt[1]) is not str:
        raise _IrregularError("bad_descriptor")
    try:
        owned = json.loads(receipt[1])
    except ValueError:
        raise _IrregularError("bad_descriptor") from None
    if type(owned) is not dict:
        raise _IrregularError("bad_descriptor")
    schema = owned.get("schema_version")
    if type(schema) is not int or schema != 3:
        return None
    state = owned.get("invocation_state")
    epoch = owned.get("epoch")
    if state not in ("ready", "invoking"):
        raise _IrregularError("bad_descriptor")
    if type(epoch) is not int or epoch != (2 if state == "invoking" else 1):
        raise _IrregularError("bad_epoch")
    operation = _hex64(owned.get("operation_digest"))
    snapshot = _hex64(owned.get("sdk_snapshot_sha256"))
    try:
        task = json.loads(receipt[2]) if type(receipt[2]) is str else None
    except ValueError:
        raise _IrregularError("bad_descriptor") from None
    if type(task) is not dict:
        raise _IrregularError("bad_descriptor")
    checkpoint = _hex64(task.get("sha256"))
    prior = getattr(context, "_completion_prior_report", None)
    if prior is not None and type(prior) is not bool:
        raise _IrregularError("bad_descriptor")
    return {
        "state": state,
        "epoch": epoch,
        "op": operation,
        "sdk": snapshot,
        "task": checkpoint,
        "prior": prior,
    }


def group_digest(digest: str) -> str:
    """A 64-hex digest as eight groups of eight characters; no decimal run in the result is longer than eight digits."""
    if type(digest) is not str or _HEX64.fullmatch(digest) is None:
        raise ValueError("digest is not 64 lowercase hex characters")
    return " ".join(digest[index : index + 8] for index in range(0, 64, 8))


def recovery_report_paragraph(context) -> str:
    """The record block for a restored run, or "" for any receipt that does not prove a started replacement (legacy schemas, `ready`)."""
    facts = _record_facts(context)
    if facts is None or facts["state"] != "invoking":
        return ""
    middle = {False: _REPORT_ABSENT, True: _REPORT_PRESENT, None: _REPORT_UNKNOWN}[facts["prior"]]
    records = (
        f"Records: SFT training operation digest {group_digest(facts['op'])}; "
        f"SDK conversation checkpoint sha256 {group_digest(facts['sdk'])}; "
        f"saved task checkpoint sha256 {group_digest(facts['task'])}."
    )
    return "\n".join((REPORT_HEADING, _REPORT_INTRO, middle, records))


def append_recovery_report(response, paragraph: str):
    """Append the block to the response message once, after one blank line; "" returns the response untouched. Nothing else changes."""
    if paragraph == "":
        return response
    message = getattr(response, "message", None)
    if type(message) is not str:
        raise ValueError("recovery record needs a text response message")
    if message == paragraph or message.endswith("\n\n" + paragraph):
        return response  # already appended: a retry adds nothing
    response.message = message + "\n\n" + paragraph if message else paragraph
    return response


def log_restore_completed(context) -> None:
    """One WARNING line after the start CAS and before the first model call: the checkpoint is restored and the continuation has started.

    The line carries the full ids of the claimed row so a reader can compare them with the run row; it does not say the run completed. A record that
    cannot be built gives one closed fallback line instead. A receipt of another schema gives nothing (no start CAS was won). Logging never changes
    the run: every failure here is swallowed.
    """
    try:
        facts, reason = None, None
        try:
            facts = _record_facts(context)
        except _IrregularError as error:
            reason = error.reason
        if reason is None and facts is None:
            return
        run_id = getattr(context, "run_id", None)
        if type(run_id) is not str or _HEX32.fullmatch(run_id) is None:
            line = f"{IRREGULAR_MARKER} run_id=none reason=bad_run_id"
        elif reason is None and facts["state"] != "invoking":
            line = f"{IRREGULAR_MARKER} run_id={run_id} reason=bad_epoch"
        elif reason is not None:
            line = f"{IRREGULAR_MARKER} run_id={run_id} reason={reason}"
        else:
            prior = {False: "absent", True: "present", None: "unknown"}[facts["prior"]]
            line = (
                f"{RESTORE_MARKER} run_id={run_id} phase=continuation_started epoch={facts['epoch']} stage={_STAGE} "
                f"operation_digest={facts['op']} sdk_snapshot_sha256={facts['sdk']} "
                f"task_checkpoint_sha256={facts['task']} prior_report={prior}"
            )
        logger.warning("%s", line)
    except Exception:
        return
