"""The recovery record in the report of a really restored run.

Cold fixture: a new process receives only the native transport DATA, claims the completion, wins the start CAS and finishes the run. The record
block that the final report carries must hold the ids of the stored run row, follow the recorded prior-report fact, and be the same text in the
streamed terminal event and in the report that `get_prompt_report` reads from the durable object.
"""

from __future__ import annotations

import asyncio
import json
import re

from normal_sft_cold_fixture import FINAL_TEXT, close, cloud_data, original_precommit, setup
from test_normal_sft_cold_continuation import child
from test_runtime_connected_warm_model import close_original_worker
from test_runtime_prompt_entry import inert_runtime_setup as inert_runtime_setup

HEADING = "## Runtime recovery record"
G8 = r"(?:[a-f0-9]{8} ){7}[a-f0-9]{8}"
RECORDS_RE = (
    r"^Records: SFT training operation digest (?P<op>"
    + G8
    + r"); SDK conversation checkpoint sha256 (?P<sdk>"
    + G8
    + r"); saved task checkpoint sha256 (?P<task>"
    + G8
    + r")\.$"
)


def _terminal(events):
    return next(event for event in reversed(events) if event.get("event") == "run_completed")


def _split(message):
    at = message.rindex("\n\n" + HEADING + "\n")
    return message[:at], message[at + 2 :]


def _check_record(state, answer, variant_words):
    final = _terminal(answer["events"])
    assert final["status"] == "response_received", final
    message = final["response"]["message"]
    assert FINAL_TEXT in message
    assert message.count(HEADING) == 1
    model_text, block = _split(message)
    assert FINAL_TEXT in model_text and HEADING not in model_text
    lines = block.split("\n")
    assert (
        len(lines) == 4
        and lines[0] == HEADING
        and lines[1].startswith("This section was generated by the runtime")
    )
    for word in variant_words["has"]:
        assert word in lines[2], (word, lines[2])
    for word in variant_words["lacks"]:
        assert word not in lines[2].lower(), (word, lines[2])
    found = re.search(RECORDS_RE, lines[3])
    assert found, lines[3]
    assert not re.search(r"\d{9,}", block), "the digests are printed in groups of eight"
    row = json.loads(answer["transport"]["ddb"]["PROMPT_RUN#" + state.run_id]["record"]["S"])
    continuation = row["continuation"]
    assert continuation["epoch"] == 2 and continuation["invocation_state"] == "invoking"
    assert found.group("op").replace(" ", "") == continuation["operation_digest"]
    assert found.group("sdk").replace(" ", "") == continuation["sdk_snapshot_sha256"]
    assert found.group("task").replace(" ", "") == row["task_checkpoint_ref"]["sha256"]
    # The streamed terminal event and the durable report read through get_prompt_report carry the same bytes.
    assert answer["report"] == [
        {
            "event": "prompt_report",
            "status": "available",
            "run_id": state.run_id,
            "found": True,
            "report": final,
        }
    ]
    assert answer["report"][0]["report"]["response"]["message"] == message
    return row, final


def test_report_of_a_restored_run_carries_the_absent_record_when_no_pause_report_was_saved(
    monkeypatch, tmp_path
):
    async def scenario():
        state = setup(monkeypatch, tmp_path)
        try:
            await original_precommit(state, monkeypatch)
            data = cloud_data(state, completed=True)
            answer = child(data, tmp_path / "replacement-without-original-report")
            row, _final = _check_record(
                state,
                answer,
                {"has": ["stopped before it saved any report", "replacement worker invocation"], "lacks": []},
            )
            assert "report_checkpoint_ref" not in row and "resumed_report_checkpoint_ref" in row, (
                "fixture precondition: the original worker saved no report, the replacement saved the final one"
            )
        finally:
            await close(state)

    asyncio.run(scenario())


def test_report_of_a_restored_run_carries_the_present_record_when_the_original_saved_its_pause_report(
    monkeypatch, tmp_path
):
    async def scenario():
        state = setup(monkeypatch, tmp_path)
        try:
            await original_precommit(state, monkeypatch)
            await close_original_worker(state.work, state.reader)
            run_key = "PROMPT_RUN#" + state.run_id
            before = json.loads(state.ports.items[run_key]["record"]["S"])
            assert type(before.get("report_checkpoint_ref")) is dict, (
                "fixture precondition: the original retained its report"
            )
            data = cloud_data(state, completed=True)
            answer = child(data, tmp_path / "replacement-after-original-report")
            _check_record(
                state,
                answer,
                {
                    "has": ["ended after saving its pause report", "later worker invocation"],
                    "lacks": ["stop", "replacement"],
                },
            )
        finally:
            await close(state)

    asyncio.run(scenario())
