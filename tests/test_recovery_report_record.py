"""Runtime-written recovery record in the final report and the restore log line.

After the start CAS of a restored run the runtime appends one short record paragraph to the response message, built from the claimed continuation
receipt and from one recorded fact (whether the original worker had saved a pause report when the replacement claimed the completion). It also
writes one WARNING line, `normal_restore_completed ...`, right after the start CAS and before the first model call. These tests drive the real
`ChatEngine.continue_normal_completion` with the fake continuation context of `test_recovery_notice`, plus the real claim and the cold-restore
fixtures for the stored report. They pin the exact text, the digit grouping, the epoch rule, the legacy byte-identity, the append-once rule, the
line format and its order, the closed fallback line, and that a suppressed logger yields no line.
"""

