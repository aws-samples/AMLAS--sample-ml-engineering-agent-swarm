def test_append_adds_one_blank_line_and_the_block_exactly_once():
    block = rn.recovery_report_paragraph(_ctx())
    response = ChatResponse(message="model text", action="a", data={"d": 1}, suggestions=["s"])
    out = rn.append_recovery_report(response, block)
    assert out is response and response.message == "model text\n\n" + block
    again = rn.append_recovery_report(response, block)
    assert again is response and response.message == "model text\n\n" + block, (
        "a second append (retry) adds nothing"
    )
    assert (response.action, response.data, response.suggestions) == ("a", {"d": 1}, ["s"])
    empty = ChatResponse(message="")
    assert rn.append_recovery_report(empty, block).message == block, "an empty message gets the block alone"
    untouched = {"turn_text": "x"}
    assert rn.append_recovery_report(untouched, "") is untouched, (
        "no paragraph: the object is returned as it is"
    )
    for bad in (SimpleNamespace(message=3), {"message": "x"}):
        with pytest.raises(ValueError):
            rn.append_recovery_report(bad, block)


