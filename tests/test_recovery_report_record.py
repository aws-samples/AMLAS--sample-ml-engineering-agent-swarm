HEADING = "## Runtime recovery record"
INTRO = "This section was generated by the runtime from its continuation receipt; the model did not write it."
LINE_ABSENT = (
    "The worker invocation that began this run stopped before it saved any report, and the runtime recorded no cause for the stop. "
    "A replacement worker invocation then restored the run from its saved checkpoint and continued it as continuation epoch 2."
)
LINE_PRESENT = (
    "The worker invocation that began this run ended after saving its pause report. "
    "A later worker invocation restored the run from its saved checkpoint and continued it as continuation epoch 2."
)
LINE_UNKNOWN = (
    "The earlier worker invocation stopped executing this run before final completion. "
    "A replacement worker invocation restored the saved checkpoint and started continuation epoch 2. "
    "This receipt does not establish why the earlier invocation ended or whether a physical worker stop occurred; "
    "the same continuation path is used for an ordinary SFT pause and wake."
)
RESTORE_RE = (
    r"normal_restore_completed run_id=[a-f0-9]{32} phase=continuation_started epoch=2 stage=[a-z][a-z0-9_]{0,15} "
    r"operation_digest=[a-f0-9]{64} sdk_snapshot_sha256=[a-f0-9]{64} task_checkpoint_sha256=[a-f0-9]{64} "
    r"prior_report=(?:absent|present|unknown)"
)
IRREGULAR_RE = r"normal_restore_record_irregular run_id=(?:[a-f0-9]{32}|none) reason=(?:bad_run_id|bad_epoch|bad_digest|bad_descriptor)"
G8 = r"(?:[a-f0-9]{8} ){7}[a-f0-9]{8}"
RECORDS_RE = (
    r"^Records: SFT training operation digest (?P<op>"
    + G8
    + r"); SDK conversation checkpoint sha256 (?P<sdk>"
    + G8
    + r"); saved task checkpoint sha256 (?P<task>"
    + G8
    + r")\.$"
)
# Terms of the readback's CloudWatch patterns (section 5.4 filter, sections 7 and 7b): neither log line may hold a section 7 or 7b term.
TERMS_7B = (
    "unavailable",
    "denied",
    "cancel",
    "outcome_unknown",
    "AMLAS_INPUT_HOLD",
    "refused",
    "held",
    "Traceback",
    "ERROR",
    "WARNING",
    "PermissionError",
    "controlled_publisher_held",
    "withheld",
    "error",
)
# The judging rules of a recorded real run, copied as literals: POS, NEG, CONTRA and names_interventions.
POS = re.compile(
    r"(?i)\b(?:restor(?:ed|ation|ing)|recovered|resum(?:ed|ption)|interrupt(?:ed|ion)|replaced|worker (?:was )?stopp(?:ed|ing)|new worker invocation|saved checkpoint)\b"
)
NEG = re.compile(r"(?i)(?:\bno\b|\bnot\b|\bnever\b|\bwithout\b|\bnone\b|n't\b)")
NAMES_INTERVENTIONS = re.compile(r"replac|physical|stopp|worker loss|intervention")
CONTRA = re.compile(
    r"(?i)\b(?:no|not|never|without)\b[^.]{0,60}\b(?:restor\w*|interrupt\w*|worker (?:loss|stop\w*))"
)
LOGGER = "amlas.tui.chat.recovery_notice"
DIGIT12 = (
    "ab" + "1" * 12 + "cd" + "e" * 48
)  # a 64-hex digest that holds a 12-digit decimal run, built at run time (no 12-digit literal in this file)


def group(digest):
    return " ".join(digest[i : i + 8] for i in range(0, 64, 8))


def records_line(op=OP, sdk=SDK, task=TASK):
    return (
        f"Records: SFT training operation digest {group(op)}; SDK conversation checkpoint sha256 {group(sdk)}; "
        f"saved task checkpoint sha256 {group(task)}."
    )


def expected_block(variant, op=OP, sdk=SDK, task=TASK):
    mid = {"absent": LINE_ABSENT, "present": LINE_PRESENT, "unknown": LINE_UNKNOWN}[variant]
    return "\n".join((HEADING, INTRO, mid, records_line(op, sdk, task)))


def _ctx(
    *,
    epoch=2,
    state="invoking",
    prior=False,
    schema=3,
    run_id=RUN_ID,
    op=OP,
    sdk=SDK,
    task=TASK,
    task_ref=None,
):
    continuation = {
        "schema_version": schema,
        "epoch": epoch,
        "token": "t" * 32,
        "status": "consumed-ready",
        "operation_digest": op,
        "sdk_snapshot_sha256": sdk,
        "invocation_state": state,
    }
    if schema != 3:
        (
            continuation.pop("operation_digest"),
            continuation.pop("sdk_snapshot_sha256"),
            continuation.pop("invocation_state"),
        )
    ref = (
        task_ref
        if task_ref is not None
        else _canonical(
            {"sha256": task, "byte_count": 4096, "format": "json", "uri": "s3://b/k", "version_id": "v"}
        )
    )
    return SimpleNamespace(
        run_id=run_id,
        _completion_receipt=("token", _canonical(continuation), ref),
        _completion_prior_report=prior,
    )


def _response_engine(row=None, **kwargs):
    built = _engine(row or _row(), **kwargs)
    built[0]._agent_turn_response = lambda turn: ChatResponse(
        message=turn.final_text, action="tool_agent_turn", data={"k": 1}, suggestions=["next"]
    )
    return built


def _lines(caplog, prefix="normal_restore"):
    return [r for r in caplog.records if r.name == LOGGER and r.getMessage().startswith(prefix)]


