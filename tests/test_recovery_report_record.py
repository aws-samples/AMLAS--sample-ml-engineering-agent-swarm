def test_variant_a_passes_the_recorded_judge_rules_and_variant_b_names_neither_stop_nor_replacement():
    a = rn.recovery_report_paragraph(_ctx(prior=False))
    assert NAMES_INTERVENTIONS.search(a.lower()), "names_interventions"
    sentences = [s.strip() for s in re.split(r"(?<=[.!?])\s+|\n+", a) if s.strip()]
    assert not [s for s in sentences if CONTRA.search(s)], "notice_contradicted must stay False"
    assert "stopped" in a and "replacement" in a
    for banned in (
        "crash",
        "killed",
        "physical",
        "interrupt",
        "lost",
        "failed",
        "timeout",
        "because",
        "automatic",
        "microvm",
        "injected",
    ):
        assert banned not in a.lower(), banned
    b = rn.recovery_report_paragraph(_ctx(prior=True))
    assert not re.search(r"(?i)stop|replac", b)
    n = rn.recovery_report_paragraph(_ctx(prior=None))
    assert not [s for s in re.split(r"(?<=[.!?])\s+|\n+", n) if CONTRA.search(s.strip())], (
        "the neutral wording is not read as a denial either"
    )


def _notice_named(text):
    """The judge's notice rule: a sentence names the restoration when a positive term is not negated in the 40 characters before it."""
    sentences = [s.strip() for s in re.split(r"(?<=[.!?])\s+|\n+", text or "") if s.strip()]
    named = any(
        not NEG.search(sentence[max(0, m.start() - 40) : m.start()])
        for sentence in sentences
        for m in POS.finditer(sentence)
    )
    contradicted = any(CONTRA.search(sentence) for sentence in sentences)
    return named, contradicted


def test_every_variant_is_read_as_naming_the_restoration_and_none_as_denying_it():
    for prior in (False, True, None):
        named, contradicted = _notice_named(rn.recovery_report_paragraph(_ctx(prior=prior)))
        assert named and not contradicted, prior
    assert _notice_named("No restoration occurred and no worker interruption was seen.") == (False, True), (
        "fixture precondition: the rule does read a denial as a denial"
    )


