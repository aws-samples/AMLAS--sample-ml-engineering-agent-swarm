def test_restore_line_is_one_closed_warning_with_the_receipt_values(caplog):
    caplog.set_level(logging.WARNING, logger=LOGGER)
    engine, _agent, _model, *_ = _response_engine()
    engine.continue_normal_completion()
    found = _lines(caplog)
    assert len(found) == 1
    record = found[0]
    assert record.levelno == logging.WARNING and record.name == LOGGER
    line = record.getMessage()
    assert re.fullmatch(RESTORE_RE, line), line
    assert line == (
        f"normal_restore_completed run_id={RUN_ID} phase=continuation_started epoch=2 stage=sft operation_digest={OP} "
        f"sdk_snapshot_sha256={SDK} task_checkpoint_sha256={TASK} prior_report=absent"
    )
    assert not _lines(caplog, "normal_restore_record_irregular")


def test_restore_line_carries_the_recorded_fact(caplog):
    caplog.set_level(logging.WARNING, logger=LOGGER)
    for prior, word in ((True, "present"), (False, "absent"), (None, "unknown")):
        caplog.clear()
        engine, *_ = _response_engine(prior=prior)
        engine.continue_normal_completion()
        assert _lines(caplog)[0].getMessage().endswith(" prior_report=" + word)


def test_restore_line_is_written_after_the_start_cas_and_before_the_first_model_call():
    engine, _agent, model, *_ = _response_engine()
    seen = []

    class Mark(logging.Handler):
        def emit(self, record):
            if record.getMessage().startswith("normal_restore"):
                seen.append(len(model.system_prompts))

    handler = Mark(logging.WARNING)
    logging.getLogger(LOGGER).addHandler(handler)
    try:
        engine.continue_normal_completion()
    finally:
        logging.getLogger(LOGGER).removeHandler(handler)
    assert seen == [0], "exactly one line, and no model call had happened yet"


