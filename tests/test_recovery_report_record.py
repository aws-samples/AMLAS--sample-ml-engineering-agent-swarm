def test_digits_are_grouped_so_no_twelve_digit_decimal_run_can_occur():
    assert re.search(r"\d{12}", DIGIT12), (
        "fixture precondition: the plain digest holds a 12-digit decimal run"
    )
    text = rn.recovery_report_paragraph(_ctx(op=DIGIT12, sdk=DIGIT12, task=DIGIT12))
    assert not re.search(r"\d{9,}", text), "no decimal run longer than one group of eight"
    assert text == expected_block("absent", DIGIT12, DIGIT12, DIGIT12)
    found = re.search(RECORDS_RE, text, re.M)
    assert found and found.group("op").replace(" ", "") == DIGIT12, (
        "a parser gets the digest back by removing the spaces"
    )
    assert rn.group_digest(DIGIT12) == group(DIGIT12)


