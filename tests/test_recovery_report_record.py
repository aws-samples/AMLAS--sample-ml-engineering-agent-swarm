@contextmanager
def _claimed(monkeypatch, with_report, mode="confirmed"):
    from test_normal_checkpoint_cas_contract import TABLE_ID, _item, _policy
    from test_normal_completion_claim_receipt import DeclaredClaimPort, _declared_claim

    from amlas.control_plane import normal_run_checkpoint as checkpoint

    context, record, stored, ready = _declared_claim()
    if with_report:
        record["report_checkpoint_ref"] = {
            "uri": "s3://declared-bucket/sessions/declared/prompt-runs/declared/reports/"
            + "a" * 64
            + ".json",
            "version_id": "declared-version",
            "sha256": "a" * 64,
            "byte_count": 512,
            "format": "json",
        }
    port = DeclaredClaimPort(context, _item(context, record), mode)
    stored_bytes = checkpoint._canonical(stored).encode("utf-8")

    @contextmanager
    def declared_native(value):
        yield port, TABLE_ID, lambda: None, None

    monkeypatch.setattr(checkpoint, "_native", declared_native)
    monkeypatch.setattr(
        checkpoint,
        "_original",
        lambda value, _r, table_id, job_name=None: (
            SimpleNamespace(operation_digest=stored["operation_digest"]),
            None,
        ),
    )
    monkeypatch.setattr(
        checkpoint, "_read_object", lambda value, _b, _ref, kind, qualify: (qualify(), stored_bytes)[1]
    )
    yield context, ready, _policy


@pytest.mark.parametrize("with_report", [False, True])
def test_the_claim_records_whether_the_original_report_pointer_existed(monkeypatch, with_report):
    with _claimed(monkeypatch, with_report) as (context, ready, policy):
        assert context._completion_prior_report is None, "nothing recorded before a claim"
        context.claim_completion(ready, policy=policy(), qualify_original=lambda: None)
        assert context._completion_prior_report is with_report
        assert type(context._completion_receipt) is tuple and len(context._completion_receipt) == 3, (
            "the receipt keeps its three strings"
        )


@pytest.mark.parametrize("mode", ["cas_failure", "readback_mismatch"])
def test_a_refused_claim_records_no_fact_and_no_receipt(monkeypatch, mode):
    with _claimed(monkeypatch, True, mode) as (context, ready, policy):
        with pytest.raises(ValueError):
            context.claim_completion(ready, policy=policy(), qualify_original=lambda: None)
        assert context._completion_prior_report is None, "a failed claim leaves no fact behind"
        assert context._completion_receipt is None
