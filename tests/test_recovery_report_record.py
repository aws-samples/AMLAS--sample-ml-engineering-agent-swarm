def _report(response):
    return {
        "event": "run_completed",
        "status": "response_received",
        "response": dataclasses.asdict(response),
        "worker_finished": True,
        "mode": "prompt",
        "run_id": RUN_ID,
        "response_kind": "conversation",
        "state_scope": "single_invocation",
        "durable_resume": False,
        "approval_policy_source": "default_noninteractive",
        "lifecycle_verified": False,
        "quality_success": False,
    }


def test_report_object_stays_closed_and_bounded_with_the_record_and_two_runs_give_identical_bytes():
    from amlas.control_plane import normal_run_checkpoint as checkpoint

    context = SimpleNamespace(run_id=RUN_ID)
    raws = []
    for _attempt in range(2):
        engine, *_ = _response_engine()
        report = _report(engine.continue_normal_completion())
        assert len(report) == 12 and set(report["response"]) == {"message", "action", "data", "suggestions"}
        raws.append(checkpoint._report_bytes(context, report))
    assert raws[0] == raws[1], "a retried continuation builds the same bytes"
    assert 0 < len(raws[0]) <= 160 * 1024
    assert json.loads(raws[0])["response"]["message"] == "done\n\n" + expected_block("absent")


